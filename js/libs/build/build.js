// Builds ../stdlib.bundle.js — the single JavaScript standard-library bundle
// embedded by js/stdlib.go. Regenerate after editing entry.js or bumping a
// dependency in package.json:
//
//   npm ci && npm run build
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import * as esbuild from "esbuild";

const dir = path.dirname(fileURLToPath(import.meta.url));

const libs = ["bignumber.js", "dayjs", "fast-xml-parser", "radashi", "zod"];
const versions = libs.map((name) => {
  const manifest = path.join(dir, "node_modules", name, "package.json");

  return `${name}@${JSON.parse(fs.readFileSync(manifest, "utf8")).version}`;
});

await esbuild.build({
  entryPoints: [path.join(dir, "entry.js")],
  outfile: path.join(dir, "..", "stdlib.bundle.js"),
  bundle: true,
  format: "iife",
  minify: true,
  banner: {
    js: `/* vef js stdlib bundle: ${versions.join(", ")} — generated by js/libs/build, do not edit */`,
  },
  plugins: [
    {
      // zod pulls all 51 locales through a single `export * as locales` of its
      // locale index; redirect that one module to the slim stub.
      name: "zod-slim-locales",
      setup(build) {
        build.onResolve({ filter: /locales\/index\.js$/ }, (args) => {
          if (!args.importer.includes(`${path.sep}zod${path.sep}`)) {
            return null;
          }

          return { path: path.join(dir, "locales.stub.js") };
        });
      },
    },
  ],
});
